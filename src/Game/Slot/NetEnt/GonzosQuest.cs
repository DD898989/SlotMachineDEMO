        public void Scanner(List<WinItem> wins)
        {
            ScanLined(wins);
            ScanScatters(wins);
        }

        public void ScanLined(List<WinItem> wins)
        {
            for (int li = 0; li < Slotx.Sel && li < BetLines.Length; li++)
            {
                var line = BetLines[li];
                int numl = 5;
                int syml = LX(1, line);

                for (int x = 2; x <= 5; x++)
                {
                    int sx = LX(x, line);
                    if (sx == wild)
                    {
                        continue;
                    }
                    else if (sx != syml)
                    {
                        numl = x - 1;
                        break;
                    }
                }

                if (numl >= 3 && syml > scat)
                {
                    double fm = Math.Min(CFN + 1, 5);
                    double mm = Slotx.FSR > 0 ? 3.0 : 1.0;
                    double pay = LinePay[syml - 1][numl - 1];

                    wins.Add(new WinItem
                    {
                        Pay = Slotx.Bet * pay,
                        MP = fm * mm,
                        Sym = syml,
                        Num = numl,
                        LI = li + 1,
                        XY = line.HitxL(numl)
                    });
                }
            }
        }

        public void ScanScatters(List<WinItem> wins)
        {
            int count = SymNum(scat);
            if (count >= 3)
            {
                wins.Add(new WinItem
                {
                    Sym = scat,
                    Num = count,
                    XY = SymPos(scat),
                    FS = 10
                });
            }
        }

        public int[][] GetReels(double mrtp)
        {
            double closest = -1000;
            int[][]? res = null;
            foreach (var (p, v) in ReelsMap)
            {
                if (Math.Abs(mrtp - p) < Math.Abs(mrtp - closest))
                {
                    closest = p;
                    res = v;
                }
            }
            return res!;
        }

        public void Spin(double mrtp, ref List<int>? cheat)
        {
            SpinReels(GetReels(mrtp), ref cheat);
        }

