        }

        public ISlotGeneric Clone()
        {
            var clone = new Jokers100Game(Slotx.Sel)
            {
                Slotx = new Slotx
                {
                    Sel = Slotx.Sel,
                    Bet = Slotx.Bet,
                    Gain = Slotx.Gain,
